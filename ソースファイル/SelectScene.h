#pragma once
#include "Scene.h"

//============================================================
// 選択画面の状態を表す列挙型
// どの選択フェーズにいるかを管理する
//============================================================
enum SelectState
{
	SELECT_GAME,        // ゲームの種類選択状態
	SELECT_DIFFICULTY,  // 単語タイピング難易度選択状態
	SELECT_MODE         // タイピング練習モード選択状態
};

//============================================================
// SelectSceneクラス
// ゲームの種類・モード・難易度を選択するシーン
//============================================================
class SelectScene:public Scene
{
private:
	//------------------------------------------------------------
	// 現在の選択状態
	//------------------------------------------------------------
	SelectState state;

	//------------------------------------------------------------
	// 画面関連
	//------------------------------------------------------------
	int selectImage;  // 背景画面
	int screenW;    // 画面幅
	int screenH;    // 画面高さ

	//------------------------------------------------------------
	// カーソル管理
	//------------------------------------------------------------
	int cursor;     // 現在選択中の項目
	int maxcursor;  // カーソルの最大値

	//------------------------------------------------------------
	// 入力管理（前フレームと現在フレーム）
	// 連続入力を防ぐために使用
	//------------------------------------------------------------
    bool prevSpace;
	bool nowSpace;

	bool prevUp;
	bool nowUp;

	bool prevDown;
	bool nowDown;

	bool prevShift;
	bool nowShift;
public:
	// コンストラクタ
	SelectScene();

	// デストラクタ
	~SelectScene();
	
	// 更新処理
	void Update()override;

	// 描画処理
	void Draw()override;
};

